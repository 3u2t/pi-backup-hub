'use strict';
const assert=require('node:assert/strict');
const progress=require('../static/progress.js');
const serverTime='2026-10-26T12:00:00Z';
const job={kind:'backup',status:'running',progress:{bytes_done:100,total_bytes:1000,percent_done:0.1,seconds_remaining:3600,seconds_elapsed:60,scan_complete:true,updated_at:serverTime}};
const network={bytes_per_second:6_000_000,measured_at:serverTime};
let view=progress.view(job,network,serverTime);
assert.equal(view.percent,10);
assert.equal(view.speed,6_000_000);
assert.equal(view.remaining,3600);
assert.equal(view.finish,'2026-10-26T13:00:00.000Z');
assert.equal(progress.duration(view.remaining),'1 Std.');
assert.equal(progress.duration(90061),'1 Tag 1 Std.');
assert.equal(progress.duration(null),'Wird berechnet');
assert.equal(progress.view({...job,status:'paused'},network,serverTime).remaining,null);
assert.equal(progress.view({...job,status:'pausing'},network,serverTime).finish,null);
assert.equal(progress.view({...job,progress:{...job.progress,scan_complete:false}},network,serverTime).remaining,null);
assert.equal(progress.view(job,network,'2026-10-26T12:01:00Z').remaining,null);
assert.equal(progress.view(job,network,'2026-10-26T12:01:00Z').speed,null);
assert.equal(progress.view({...job,progress:{...job.progress,percent_done:1}},network,serverTime).percent,99.9);
assert.equal(progress.view({status:'queued'},null,serverTime).percent,null);
assert.equal(progress.view(job,{bytes_per_second:NaN,measured_at:serverTime},serverTime).speed,null);
console.log('Progress, pause, ETA and network-rate checks passed');
